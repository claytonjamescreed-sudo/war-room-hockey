// opens, how it signs off, its shouts for a big night, and a closing thought (its "saying of the
// day"). brief.ts goes through every list in turn, so a line comes back only once the rest of its
// list has been used: with five booths taking turns, a booth's 40 sayings last about 200 game
// days, a whole season.
//
// Only a handful of these are things the broadcasters are known for saying; they're marked
// "sourced" below, with where they come from. Everything else is our own writing in each
// broadcaster's spirit (the page says the recap is "called in the spirit of" them), and must never
// be presented as their words. Keep Jim Robson's and John Garrett's booths affectionate: both died
// in 2026.
//
// Sourced lines and bits:
// - John Shorthouse: "Lets it go, he scores!" (Daniel Sedin, his last home game, followed by
//   two and a half minutes of letting the crowd speak) and "They've slayed the dragon!" (Alex
//   Burrows, 2011). CanucksArmy, "Top five play-by-play calls in Canucks history".
// - Jim Robson: his hello to "the hospital patients and shut-ins" (Wikipedia; CP24, Feb 2026),
//   "Greg Adams! Greg Adams!" (1994) and "He will play, you know he will play!" (Trevor Linden,
//   1994 Final). CanucksArmy, as above.
// - Don Taylor: "you're up to date in the world of sports" (BC Sports Hall of Fame), "the mesh
//   ripples", top shelf "where Grandma keeps the peanut butter", saves "in rapier-like fashion"
//   and "scintillating" after Danny Gallivan, a goalie "like a modern-day Gerry Cheevers", Marv
//   Albert's "Yes!" and "gorgeous move", Jim Van Horne's moustache and Hazel Mae as fight judges,
//   the Sports Page (Wikipedia; Daily Hive, "Vancouver fans' favourite Don Taylor-isms").
// - John Garrett: ketchup, "the sauce that made everything taste good", and a Kraft Dinner that
//   needed "a little bit of ketchup"; the hot dog in his pads with the Nordiques; "Lotto" for a
//   6.49 goals-against average; his cup-half-full optimism and his superstitions (Wikipedia; The
//   Hockey News; Scout Magazine; CanucksArmy).
// - Tom Larscheid: Robson's "trumpet player", his own "if there's a yin and yang, we were it", the
//   Fisherman's Friends he teased Robson about, his "don't count your chickens" (as paraphrased by
//   the Vancouver Sun), and wishing he'd got to say "the Vancouver Canucks are Stanley Cup
//   champions" (Vancouver Sun, "Broadcasters own a place in Canucks history"; Wikipedia).

